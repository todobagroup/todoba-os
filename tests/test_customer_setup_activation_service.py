"""
TODOBA Customer Setup Activation Service Tests

Owner contract:
- one activation request creates one setup right
- setup_activation_id is generated by TODOBA
- one customer may own multiple setup rights
- one setup right may bind to at most one deployment
- one deployment may consume at most one setup right
- activation retry is idempotent
- activation retry never implicitly reactivates SUSPENDED
- activation retry never changes BOUND deployment truth
- cross-customer request reuse fails closed
- cross-customer deployment binding fails closed
- BOUND is terminal for setup-right ownership
- restored orphaned/cross-customer truth fails closed
- durable state advances before RAM state
- setup-right persistence contains no payment, account,
  credential, secret, package, or runtime entitlement data
"""

