"""
TODOBA Customer Registration Service Tests

Owner contract:
- registration identity is registration_request_id
- customer_id is generated by TODOBA
- one request owns exactly one customer_id
- one generated customer_id cannot belong to two requests
- identical retry is idempotent
- durable registration is written before downstream
  CustomerIdentity registration
- retry repairs missing downstream CustomerIdentity using
  the persisted customer_id
- registration state contains no profile, payment,
  deployment, credential, secret, entitlement, or package
  material
"""

import json
from pathlib import Path
from types import SimpleNamespace

import pytest

import backend.commercial.customer_registration_service as registration_module
from backend.commercial.customer_identity_registry import (
    CustomerIdentity,
    CustomerIdentityRegistry,
)
from backend.commercial.customer_registration_service import (
    CustomerRegistrationRecord,
    CustomerRegistrationResult,
    CustomerRegistrationService,
    CustomerRegistrationStore,
)


def build_environment(
    tmp_path: Path,
) -> tuple[
    CustomerRegistrationStore,
    CustomerIdentityRegistry,
    CustomerRegistrationService,
]:
    identity_registry = CustomerIdentityRegistry(
        tmp_path
        / "customer_identities.json"
    )
    identity_registry.initialize_empty()

    registration_store = CustomerRegistrationStore(
        tmp_path
        / "customer_registrations.json"
    )
    registration_store.initialize_empty()

    service = CustomerRegistrationService(
        registration_store=registration_store,
        customer_identity_registry=identity_registry,
    )

    return (
        registration_store,
        identity_registry,
        service,
    )


