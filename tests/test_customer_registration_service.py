def test_registration_persistence_contains_only_owned_fields(
    tmp_path: Path,
) -> None:
    (
        registration_store,
        _,
        service,
    ) = build_environment(
        tmp_path
    )

    service.register(
        registration_request_id="registration-001"
    )

    payload = json.loads(
        registration_store.storage_path.read_text(
            encoding="utf-8",
        )
    )

    assert set(
        payload
    ) == {
        "version",
        "records",
    }

    assert len(
        payload["records"]
    ) == 1

    record = payload[
        "records"
    ][0]

    assert set(
        record
    ) == {
        "registration_request_id",
        "customer_id",
    }

    forbidden_fields = {
        "email",
        "phone",
        "password",
        "profile",
        "payment_id",
        "subscription_id",
        "deployment_id",
        "agent_id",
        "account_fingerprint",
        "credential_id",
        "access_credential",
        "secret",
        "entitlement",
        "package_path",
        "package_root",
    }

    assert forbidden_fields.isdisjoint(
        record
    )


