def test_store_suspend_and_reactivate_are_idempotent(
    tmp_path: Path,
) -> None:
    store = CustomerSetupActivationStore(
        tmp_path
        / "activations.json"
    )
    store.initialize_empty()

    record = store.register(
        CustomerSetupActivationRecord(
            activation_request_id="request-001",
            setup_activation_id=(
                "setup-activation-001"
            ),
            customer_id="customer-001",
            status=(
                CustomerSetupActivationStatus.ACTIVE
            ),
        )
    )

    suspended = store.suspend(
        setup_activation_id=(
            record.setup_activation_id
        )
    )

    assert (
        suspended.status
        is CustomerSetupActivationStatus.SUSPENDED
    )

    assert (
        store.suspend(
            setup_activation_id=(
                record.setup_activation_id
            )
        )
        == suspended
    )

    active = store.reactivate(
        setup_activation_id=(
            record.setup_activation_id
        )
    )

    assert (
        active.status
        is CustomerSetupActivationStatus.ACTIVE
    )

    assert (
        store.reactivate(
            setup_activation_id=(
                record.setup_activation_id
            )
        )
        == active
    )


